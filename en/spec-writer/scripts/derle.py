def sema():
    isaret = {"type": "string", "pattern": "BEKLİYOR"}
    bolumler = {}
    for b in T["bolumler"]:
        if b.get("turetilmis"):
            continue
        dolu = {"type": "object", "additionalProperties": False, "properties": {"mermaid": {"type": "string"}}}
        if b["alanlar"]:
            dolu["properties"]["alanlar"] = {"type": "object", "additionalProperties": False, "required": [a["anahtar"] for a in b["alanlar"]],
                                            "properties": {a["anahtar"]: {"type": "string", "minLength": 1} for a in b["alanlar"]}}
            dolu["required"] = ["alanlar"]
        if b["sutunlar"]:
            ogeler = []
            for c in b["sutunlar"]:
                if c.get("secenekler"):
                    ogeler.append({"anyOf": [{"enum": c["secenekler"]}, isaret]})
                elif c.get("kimlik"):
                    ogeler.append({"type": "string", "pattern": "^(" + "|".join(c["kimlik"]) + ")-[0-9]{2,3}$"})
                else:
                    ogeler.append({"type": "string", "minLength": 1})
            dolu["properties"]["satirlar"] = {"type": "array", "minItems": b["en_az_satir"],
                                             "items": {"type": "array", "items": ogeler, "minItems": len(ogeler), "maxItems": len(ogeler)}}
            dolu.setdefault("required", []).append("satirlar")
        gecersiz = {"type": "object", "additionalProperties": False, "required": ["gecerli", "gerekce"],
                    "properties": {"gecerli": {"const": False}, "gerekce": {"type": "string", "minLength": 1}}}
        bolumler[b["no"]] = dolu if b["sinif"] == "Kritik" else {"oneOf": [dolu, gecersiz]}
    dizi = lambda n: {"type": "array", "items": {"type": "array", "items": {"type": "string"}, "minItems": n, "maxItems": n}}
    return {"$schema": "http://json-schema.org/draft-07/schema#", "title": "Belirtim Yazmanı FS-TS içeriği", "type": "object",
            "required": ["sema", "meta", "turler", "profil", "bolumler"], "additionalProperties": False,
            "properties": {"sema": {"const": T["sema"]},
                           "meta": {"type": "object", "required": ["surum", "tarih", "hazirlayan", "durum"],
                                    "properties": {k: {"type": "string"} for k in ("surum", "tarih", "hazirlayan", "durum", "musteri")}},
                           "turler": {"type": "array", "minItems": 1, "uniqueItems": True, "items": {"enum": [t["kod"] for t in T["tur_tanimlari"]]}},
                           "profil": {"enum": list(T["profiller"])},
                           "bolumler": {"type": "object", "additionalProperties": False, "properties": bolumler},
                           "surum_gecmisi": dizi(4), "onaylar": dizi(3), "nesne_degil": {"type": "array", "items": {"type": "string"}}}}


