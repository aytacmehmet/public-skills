def sekil(dil="en"):
    M = SEKIL_METIN.get(dil, SEKIL_METIN["en"])
    out = [BAS, M["legend"].format(turler=", ".join(f"{t['kod']} = {t['ad']}" for t in T["tur_tanimlari"])), ""]
    for b in T["bolumler"]:
        alanlar = ", ".join(a["anahtar"] + ("†" if a.get("karar") else "") + (" [" + "|".join(a["secenekler"]) + "]" if a.get("secenekler") else "")
                            for a in b["alanlar"]) or "—"
        if b.get("turetilmis"):
            sutunlar = M["derived"]
        elif not b["sutunlar"]:
            sutunlar = "—"
        else:
            sutunlar = "; ".join(("{" + "/".join(c["kimlik"]) + "}" if c.get("kimlik") else c["ad"])
                                 + (" [" + "|".join(c["secenekler"]) + "]" if c.get("secenekler") else "") + ("†" if c.get("karar") else "")
                                 for c in b["sutunlar"])
        ek = M["min"].format(n=b["en_az_satir"]) if b["en_az_satir"] > 1 else ""
        out.append(f"{b['no']} {b['baslik']} | {b['agirlik']} {b['sinif'][0]} | {','.join(b['turler'])} | {alanlar} | {sutunlar}{ek}")
    liste = ", ".join(f"{b['no']} ({M['all'] if '*' in b['bonus_acilis'] else '/'.join(b['bonus_acilis']) or M['tam']})"
                      for b in T["bolumler"] if b["sinif"] == "Bonus")
    out += ["", M["bonus"].format(liste=liste), M["n54"], M["n34"], SON]
    return "\n".join(out)


def hedefler():
    h = {os.path.join("references", d): bolum_dosyasi(g, ad) for d, g, ad in DOSYA_GRUPLARI}
    h[os.path.join("references", "yazim.md")] = yazim()
    h[os.path.join("references", "denetim.md")] = denetim()
    h[os.path.join("assets", "icerik-semasi.json")] = json.dumps(sema(), ensure_ascii=False, indent=1) + "\n"
    skill = os.path.join(KOK, "SKILL.md")
    if os.path.exists(skill):
        s = open(skill, encoding="utf-8").read()
        if BAS in s and SON in s:
            dil = re.search(r'(?m)^\s*language:\s*"?(tr|en)"?\s*$', s[:s.index(BAS)])
            # Instructions are English in both language packages; the shape block always uses the English legend.
            h["SKILL.md"] = s[:s.index(BAS)] + sekil("en") + s[s.index(SON) + len(SON):]
    return h


def main():
    kontrol = "--kontrol" in sys.argv
    fark = []
    for yol, icerik in hedefler().items():
        tam = os.path.join(KOK, yol)
        mevcut = open(tam, encoding="utf-8").read() if os.path.exists(tam) else None
        if mevcut != icerik:
            fark.append(yol)
            if not kontrol:
                os.makedirs(os.path.dirname(tam), exist_ok=True)
                with open(tam, "w", encoding="utf-8", newline="\n") as f:  # LF on every platform
                    f.write(icerik)
    if kontrol:
        print("Derived files are up to date." if not fark else "Out of date: " + ", ".join(fark) + " → python scripts/derle.py")
        sys.exit(1 if fark else 0)
    print("Written: " + (", ".join(fark) if fark else "no change"))


if __name__ == "__main__":
    main()
