def bolum_dosyasi(gruplar, ad):
    out = [f"# Section writing guide · {ad}", "",
           "Generated file (source: assets/tanim.json). Column numbers start at 0 and follow the array order in the JSON. "
           "{X-nn} is the row id; [a | b] takes only these values; (KARAR) = do not decide yourself, mark it when the inputs do not state it.", ""]
    for b in T["bolumler"]:
        if b["grup"] in gruplar:
            out += [bv.bilgi_metni(b, ornek=True), "Good practice: " + b["pratik"], ""]
    return "\n".join(out).rstrip() + "\n"


